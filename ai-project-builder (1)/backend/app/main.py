@app.get("/api/projects/{project_id}/download")
def download(project_id: str):
    p=get_project(project_id); buf=io.BytesIO()
    excluded=(".env",".env.local",".env.production","id_rsa","credentials.json")
    with zipfile.ZipFile(buf,"w",zipfile.ZIP_DEFLATED) as z:
        for path,content in p["files"].items():
            path=safe_path(path)
            if path in excluded or any(x in path.split("/") for x in ("node_modules","__pycache__",".git","dist","build")): continue
            z.writestr(path,content)
    buf.seek(0)
    return StreamingResponse(buf,media_type="application/zip",headers={"Content-Disposition":f'attachment; filename="ai-project-{project_id[:8]}.zip"'})

@app.get("/api/github/login")
def github_login(request: Request):
    cid=os.getenv("GITHUB_CLIENT_ID")
    if not cid: raise HTTPException(503,"Configure GITHUB_CLIENT_ID and GITHUB_CLIENT_SECRET in backend/.env")
    state=secrets.token_urlsafe(32); request.session["oauth_state"]=state; request.session.setdefault("session_id", secrets.token_urlsafe(32))
    params={"client_id":cid,"redirect_uri":os.getenv("GITHUB_CALLBACK_URL","http://localhost:8000/api/github/callback"),"scope":"repo","state":state}
    return RedirectResponse("https://github.com/login/oauth/authorize?"+urlencode(params))

@app.get("/api/github/callback")
async def github_callback(request: Request, code: str="", state: str=""):
    expected=request.session.pop("oauth_state",None)
    if not expected or not secrets.compare_digest(expected,state):
        raise HTTPException(400,"Invalid OAuth state. Please restart GitHub login.")
    try:
        async with httpx.AsyncClient(timeout=30) as client:
            token_resp=await client.post("https://github.com/login/oauth/access_token",headers={"Accept":"application/json"},json={"client_id":os.getenv("GITHUB_CLIENT_ID"),"client_secret":os.getenv("GITHUB_CLIENT_SECRET"),"code":code,"redirect_uri":os.getenv("GITHUB_CALLBACK_URL","http://localhost:8000/api/github/callback")})
            token_resp.raise_for_status(); token_data=token_resp.json()
            if not token_data.get("access_token"): raise HTTPException(502,"GitHub did not return an access token")
            sid=request.session.setdefault("session_id", secrets.token_urlsafe(32))
            conn=db(); conn.execute("INSERT INTO github_tokens(session_id,access_token) VALUES(?,?) ON CONFLICT(session_id) DO UPDATE SET access_token=excluded.access_token",(sid,token_data["access_token"])); conn.commit(); conn.close()
    except httpx.HTTPError as e: raise HTTPException(502,f"GitHub OAuth failed: {e}")
    return RedirectResponse(os.getenv("FRONTEND_URL","http://localhost:5173")+"?github=connected")

async def gh_request(request: Request, method: str, url: str, **kwargs):
    sid=request.session.get("session_id")
    conn=db(); row=conn.execute("SELECT access_token FROM github_tokens WHERE session_id=?",(sid,)).fetchone() if sid else None; conn.close()
    token=row[0] if row else None
    if not token: raise HTTPException(401,"Connect GitHub first.")
    async with httpx.AsyncClient(timeout=45) as client:
        r=await client.request(method,url,headers={"Authorization":f"Bearer {token}","Accept":"application/vnd.github+json","X-GitHub-Api-Version":"2022-11-28",**kwargs.pop("headers",{})},**kwargs)
    if r.status_code>=400:
        detail=r.text[:700]
        code=429 if r.status_code==429 else (409 if r.status_code==409 else 502)
        raise HTTPException(code,f"GitHub API error ({r.status_code}): {detail}")
    return r.json() if r.content else {}

