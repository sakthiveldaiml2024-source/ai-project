@app.post("/api/github/publish")
async def github_publish(body: PublishBody, request: Request):
    if not body.confirm: raise HTTPException(400,"Explicit confirmation is required before publishing.")
    if body.visibility not in ("public","private"): raise HTTPException(400,"Visibility must be public or private.")
    if body.existing_repo:
        if not re.fullmatch(r"[A-Za-z0-9_.-]{1,100}/[A-Za-z0-9._-]{1,100}",body.repo_name): raise HTTPException(400,"For an existing repository, use owner/repository.")
    elif not re.fullmatch(r"[A-Za-z0-9._-]{1,100}",body.repo_name): raise HTTPException(400,"Repository name contains unsupported characters.")
    p=get_project(body.project_id); sid=request.session.get("session_id")
    conn=db(); row=conn.execute("SELECT access_token FROM github_tokens WHERE session_id=?",(sid,)).fetchone() if sid else None; conn.close()
    token=row[0] if row else None
    if not token: raise HTTPException(401,"Connect GitHub first.")
    if body.existing_repo:
        repo=await gh_request(request,"GET",f"https://api.github.com/repos/{body.repo_name}")
    else:
        repo=await gh_request(request,"POST","https://api.github.com/user/repos",json={"name":body.repo_name,"description":body.description,"private":body.visibility=="private","auto_init":True})
    owner=repo["owner"]["login"]; name=repo["name"]; branch=body.branch.strip() or repo.get("default_branch","main")
    # For each file, use contents API; sequential requests avoid race conditions and report the actual result.
    published=[]
    for path,content in sorted(p["files"].items()):
        path=safe_path(path)
        if path in (".env",".env.local",".env.production","credentials.json","id_rsa") or any(x in path.split("/") for x in ("node_modules","__pycache__",".git","dist","build")): continue
        encoded=base64.b64encode(content.encode()).decode()
        url=f"https://api.github.com/repos/{owner}/{name}/contents/{path}"
        headers={}
        try:
            existing=await gh_request(request,"GET",url,params={"ref":branch})
            headers["If-Match"]=existing.get("sha","")
            payload={"message":f"Update {path} via AI Project Builder","content":encoded,"branch":branch,"sha":existing.get("sha")}
        except HTTPException as e:
            if e.status_code not in (404,): raise
            payload={"message":f"Add {path} via AI Project Builder","content":encoded,"branch":branch}
        result=await gh_request(request,"PUT",url,json=payload)
        published.append(path)
    return {"success":True,"repository_url":repo["html_url"],"branch":branch,"published_count":len(published),"files":published}
