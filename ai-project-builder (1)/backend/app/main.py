@app.post("/api/projects/analyze")
async def analyze(topic: str = Form(""), stack: str = Form("React + Vite, FastAPI, Python"), file: Optional[UploadFile] = File(None)):
    if file:
        extracted=await extract_upload(file)
        topic=(topic+"\n\nExtracted specification:\n"+extracted).strip()
    if len(topic)<10: raise HTTPException(400,"Enter a project specification or upload a document with readable text.")
    if len(topic)>30000: topic=topic[:30000]
    answer=await ai_chat("You are a senior software architect. Analyze project requirements accurately. Return concise JSON with keys: summary, features (array), architecture (array), risks (array), suggested_files (array). No markdown fences.", f"Technology preference: {stack}\nProject specification:\n{topic}")
    try:
        match=re.search(r"\{.*\}",answer,re.S)
        analysis=json.loads(match.group(0) if match else answer)
    except Exception: analysis={"summary":answer,"features":[],"architecture":[],"risks":[],"suggested_files":[]}
    return {"analysis":analysis,"topic":topic,"stack":stack}

@app.post("/api/projects/generate")
async def generate(body: GenerateBody):
    prompt=f"""Build a complete, coherent project codebase. Topic/specification:\n{body.topic}\nPreferred stack: {body.stack}\nProject name: {body.project_name}\n\nReturn ONLY valid JSON object mapping relative file paths to complete text contents, e.g. {{\"README.md\":\"...\",\"src/main.py\":\"...\"}}. Include runnable implementation, dependencies, tests where appropriate, README setup instructions, .gitignore, and .env.example. Do not include secrets or real .env files. Keep scope practical but implement core functionality. Include no markdown fences. Maximum 30 files; avoid binaries, node_modules, caches and build output."""
    raw=await ai_chat("You are an expert full-stack engineer. Output valid JSON only. File paths must be relative and safe. Every file must be complete, not a placeholder.",prompt)
    try:
        match=re.search(r"\{.*\}",raw,re.S)
        files=sanitize_files(json.loads(match.group(0) if match else raw))
    except HTTPException: raise
    except Exception: raise HTTPException(502,"AI returned invalid JSON. Try a more specific prompt or a model with reliable JSON output.")
    project_id=str(uuid.uuid4())
    conn=db()
    conn.execute("INSERT INTO projects(id,topic,stack,files) VALUES(?,?,?,?)",(project_id,body.topic,body.stack,json.dumps(files)))
    conn.commit(); conn.close()
    return {"project_id":project_id,"files":[{"path":k,"size":len(v.encode())} for k,v in sorted(files.items())],"count":len(files)}

def get_project(pid):
    conn=db(); row=conn.execute("SELECT topic,stack,files FROM projects WHERE id=?",(pid,)).fetchone(); conn.close()
    if not row: raise HTTPException(404,"Project not found")
    return {"topic":row[0],"stack":row[1],"files":json.loads(row[2])}

