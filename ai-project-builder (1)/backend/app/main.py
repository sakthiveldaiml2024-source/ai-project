def safe_path(path: str) -> str:
    path = path.replace("\\", "/").strip()
    p = PurePosixPath(path)
    if not path or p.is_absolute() or any(part in ("..", ".") for part in p.parts) or re.match(r"^[A-Za-z]:", path):
        raise HTTPException(400, f"Unsafe file path: {path[:100]}")
    if len(path) > 240 or path.startswith(".git/"):
        raise HTTPException(400, "Invalid generated file path")
    return str(p)

def sanitize_files(raw):
    if not isinstance(raw, dict) or not raw:
        raise HTTPException(502, "AI provider returned no files")
    out={}
    forbidden=(".env", ".env.local", ".env.production", "id_rsa", "credentials.json")
    for k,v in raw.items():
        path=safe_path(str(k))
        if path in forbidden or path.endswith((".pyc", ".db")) or any(x in path.split("/") for x in ("node_modules","__pycache__",".git","dist","build")):
            continue
        if not isinstance(v,str): continue
        out[path]=v[:500_000]
    if not out: raise HTTPException(502, "AI response contained no usable source files")
    out.setdefault("README.md", "# Generated Project\n\nGenerated by AI Project Builder. Review all code before running.")
    out.setdefault(".gitignore", ".env\nnode_modules/\n.venv/\n__pycache__/\ndist/\nbuild/\n")
    out.setdefault(".env.example", "# Add required environment variables here; never commit real secrets.\n")
    return out

