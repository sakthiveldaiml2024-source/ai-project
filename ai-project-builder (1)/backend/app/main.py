async def extract_upload(upload: UploadFile) -> str:
    data=await upload.read(MAX_UPLOAD+1)
    if len(data)>MAX_UPLOAD: raise HTTPException(413, f"File exceeds {MAX_UPLOAD//(1024*1024)} MB limit")
    name=(upload.filename or "").lower()
    if name.endswith(".txt") or name.endswith(".md"):
        return data.decode("utf-8", errors="replace")
    if name.endswith(".pdf"):
        try:
            from pypdf import PdfReader
            reader=PdfReader(io.BytesIO(data))
            return "\n".join((p.extract_text() or "") for p in reader.pages)[:30000]
        except Exception as e: raise HTTPException(400, f"Could not parse PDF: {e}")
    if name.endswith(".docx"):
        try:
            from docx import Document
            doc=Document(io.BytesIO(data))
            return "\n".join(p.text for p in doc.paragraphs)[:30000]
        except Exception as e: raise HTTPException(400, f"Could not parse DOCX: {e}")
    if name.endswith((".png",".jpg",".jpeg",".webp",".bmp")):
        try:
            from PIL import Image
            import pytesseract
            return pytesseract.image_to_string(Image.open(io.BytesIO(data)))[:30000]
        except Exception as e: raise HTTPException(400, "Image OCR failed. Install Tesseract OCR and verify pytesseract is configured.")
    raise HTTPException(415, "Supported file types: PDF, DOCX, TXT, MD, PNG, JPG, WEBP")

async def ai_chat(system: str, prompt: str) -> str:
    key=os.getenv("AI_API_KEY")
    if not key: raise HTTPException(503, "AI is not configured. Add AI_API_KEY to backend/.env.")
    base=os.getenv("AI_BASE_URL","https://api.openai.com/v1").rstrip("/")
    model=os.getenv("AI_MODEL","gpt-4.1-mini")
    try:
        async with httpx.AsyncClient(timeout=180) as client:
            r=await client.post(base+"/chat/completions", headers={"Authorization":f"Bearer {key}","Content-Type":"application/json"}, json={"model":model,"temperature":0.2,"messages":[{"role":"system","content":system},{"role":"user","content":prompt}]})
            if r.status_code>=400: raise HTTPException(502, f"AI provider error ({r.status_code}): {r.text[:500]}")
            return r.json()["choices"][0]["message"]["content"]
    except httpx.RequestError as e: raise HTTPException(502, f"Could not reach AI provider: {e}")

